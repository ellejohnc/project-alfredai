import { useQuery } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';

type TableName = 'webinars_events' | 'guides_playbooks' | 'blog_posts' | 'testimonials' | 'faqs' | 'documentation';

// Generic hook with React Query for caching and deduplication
export function usePublishedContent<T extends { id: string }>(
  tableName: TableName,
  options?: {
    orderBy?: string;
    ascending?: boolean;
  }
) {
  const { orderBy = 'created_at', ascending = false } = options || {};

  return useQuery({
    queryKey: ['published', tableName],
    queryFn: async () => {
      const { data, error } = await supabase
        .from(tableName)
        .select('*')
        .eq('status', 'published')
        .order(orderBy, { ascending });

      if (error) throw error;
      return (data || []) as unknown as T[];
    },
    staleTime: 5 * 60 * 1000, // 5 minutes
    gcTime: 10 * 60 * 1000, // 10 minutes cache
  });
}

// Specific typed hooks for each content type
export interface PublishedBlogPost {
  id: string;
  title: string;
  slug: string | null;
  excerpt: string | null;
  content: string | null;
  category: string | null;
  tags: string[] | null;
  featured_image_url: string | null;
  published_at: string | null;
  created_at: string;
  updated_at: string;
  /**
   * Editor overrides for search and social. Null on every existing row, and the
   * consumers fall back to title/excerpt, so these are additive by design — a
   * new SEO field that blanks every meta description the day it ships is worse
   * than not having one.
   *
   * Optional rather than required on purpose: the columns landed today and the
   * generated `types.ts` is regenerated by Lovable, not by us, so it does not
   * carry them yet. Optional is also simply true of a nullable column nothing
   * has written to.
   */
  seo_title?: string | null;
  seo_description?: string | null;
}


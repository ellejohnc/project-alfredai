import js from "@eslint/js";
import globals from "globals";
import reactHooks from "eslint-plugin-react-hooks";
import reactRefresh from "eslint-plugin-react-refresh";
import tseslint from "typescript-eslint";

export default tseslint.config(
  { ignores: ["dist"] },
  {
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    files: ["**/*.{ts,tsx}"],
    languageOptions: {
      ecmaVersion: 2020,
      globals: globals.browser,
    },
    plugins: {
      "react-hooks": reactHooks,
      "react-refresh": reactRefresh,
    },
    rules: {
      ...reactHooks.configs.recommended.rules,
      "react-refresh/only-export-components": ["warn", { allowConstantExport: true }],
      // ON since 26 Aug. It was off, and that is precisely why two dead bindings
      // sat in App.tsx unnoticed after MobileBottomNav was deleted, and why a
      // whole scroll-hide effect in ChatAssistant kept running on every mobile
      // scroll while nothing read the state it set. Nothing said a word about
      // either — a deleted component leaves its leftovers behind silently, and
      // this is the only rule that ever notices.
      //
      // Turning it on is cheap now that eslint-suppressions.json exists: the
      // existing debt is pinned per file and rule, so only NEW dead code fails.
      // An underscore prefix is the deliberate opt-out for a binding that has to
      // exist but is not used — a positional argument, a destructured discard.
      "@typescript-eslint/no-unused-vars": ["error", {
        argsIgnorePattern: "^_",
        varsIgnorePattern: "^_",
        caughtErrorsIgnorePattern: "^_",
        destructuredArrayIgnorePattern: "^_",
      }],
      // Promoted from warn to error on purpose, and it is not a tightening of
      // the bar — it is what lets ESLint's own bulk suppressions hold the line
      // instead of our hand-rolled count file. Suppressions only ever apply to
      // errors, so as a warning this rule could not be pinned per file and had
      // to be counted in aggregate. Counting is the weak version: a new
      // violation hides behind a fixed one and the total never moves.
      //
      // Every existing violation is pinned in eslint-suppressions.json, so the
      // day-to-day experience is unchanged. Only a NEW one fails.
      "react-hooks/exhaustive-deps": "error",
    },
  },
  {
    // src/components/ui is shadcn's output directory — see components.json,
    // which points the "ui" alias here. These files are regenerated by
    // `npx shadcn add <component>`, which overwrites them wholesale from the
    // upstream registry.
    //
    // Seven of them export a variant helper or a hook beside the component:
    // buttonVariants, badgeVariants, toggleVariants, navigationMenuTriggerStyle,
    // useFormField, useSidebar, and sonner's toast. Splitting those out is easy
    // — they have one to four import sites each — but it does not hold: the
    // next component update writes the upstream file back, the export returns,
    // and the split silently becomes a duplicate definition nobody notices.
    //
    // So the rule is off HERE and nowhere else. Everything we author, including
    // the app-written files that used to sit in this directory, was fixed
    // properly rather than exempted.
    files: ["src/components/ui/**/*.{ts,tsx}"],
    rules: {
      "react-refresh/only-export-components": "off",
    },
  },
  {
    // Lovable regenerates these two wholesale — both carry
    // "This file is automatically generated. Do not edit it directly." at the
    // top, and both are rewritten when the Supabase integration changes.
    //
    // A `let` that is assigned once in previewAuthStorage.ts turned CI red on a
    // Lovable push. Fixing it in place works exactly until the next
    // regeneration puts it back, and then the gate goes red again on a commit
    // nobody here wrote. Exempting them is honest about who owns the code: we
    // do not author it and cannot keep a fix in it.
    //
    // Scoped to these two files by name, not the directory, so anything we DO
    // author under src/integrations stays gated like the rest of the app.
    files: [
      "src/integrations/supabase/client.ts",
      "src/integrations/supabase/previewAuthStorage.ts",
    ],
    rules: {
      "prefer-const": "off",
    },
  },
);
